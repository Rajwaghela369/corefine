"""GPAW (PAW, plane-wave mode): a short Python script plus structure.json; GPAW is driven through ASE.

Defaults are GPAW's own: PW(ecut=340 eV) from gpaw.PW, Fermi-Dirac occupations, PAW setups from the
gpaw-data package. The request sets the functional and a Γ-centred k-mesh; basis_scale multiplies ecut.
Energies are relative to isolated atoms (GPAW's reference), fine within one code (EOS, convergence).
"""

import re
from pathlib import Path

from ase.io import read as ase_read
from ase.io import write as ase_write

from app.config import Settings
from app.dft.codes.base import CodeAdapter, ReadBack, Results
from app.dft.request import CalcRequest
from app.dft.structure import Cell

XC = {"PBE": "PBE", "PBEsol": "PBEsol", "LDA": "LDA"}
DEFAULT_ECUT_EV = 340.0  # gpaw.PW() default (checked in gpaw 26.7.0)

SCRIPT = '''"""Generated by CoRefine. Run with: gpaw python gpaw_scf.py"""
from ase.io import read
from gpaw import GPAW, PW

atoms = read("structure.json")
atoms.calc = GPAW(mode=PW({ecut}), xc="{xc}", kpts={{"size": ({k1}, {k2}, {k3}), "gamma": True}}, txt="gpaw.txt")
energy = atoms.get_potential_energy()
print(f"CoRefine: energy {{energy:.8f}} eV")
'''


class GpawAdapter(CodeAdapter):
    name, label, method, main_file = "gpaw", "GPAW", "PAW, plane waves (ASE/Python)", "gpaw_scf.py"
    program = "gpaw"

    def availability(self, s: Settings) -> tuple[bool, str]:
        return True, "inputs need no external data; runs need GPAW (installable)"

    def functionals(self) -> dict[str, str]:
        return XC

    def write(self, cell: Cell, req: CalcRequest, outdir: Path, s: Settings, title: str) -> dict:
        outdir.mkdir(parents=True, exist_ok=True)
        ase_write(outdir / "structure.json", cell.atoms, format="json")
        ecut = round(DEFAULT_ECUT_EV * req.basis_scale, 3)
        k1, k2, k3 = req.kmesh
        (outdir / "gpaw_scf.py").write_text(SCRIPT.format(ecut=ecut, xc=XC[req.functional], k1=k1, k2=k2, k3=k3))
        return {"files": ["gpaw_scf.py", "structure.json"],
                "set_explicitly": {"xc": XC[req.functional], "kpts": f"{k1}x{k2}x{k3}, Gamma-centred",
                                   **({"ecut": f"{ecut} eV (x{req.basis_scale} the default)"} if req.basis_scale != 1 else {})},
                "defaults": {"source": "GPAW defaults (gpaw 26.7.0)",
                             "values": {**({"ecut_eV": DEFAULT_ECUT_EV} if req.basis_scale == 1 else {}),
                                        "occupations": "Fermi-Dirac (GPAW default)", "setups": "gpaw-data PAW"}}}

    def read_back(self, outdir: Path, req: CalcRequest) -> ReadBack:
        atoms = ase_read(outdir / "structure.json")
        text = (outdir / "gpaw_scf.py").read_text()
        k = re.search(r'"size":\s*\((\d+),\s*(\d+),\s*(\d+)\),\s*"gamma":\s*(True|False)', text)
        xc = re.search(r'xc="([^"]+)"', text)
        extra = [{"check": "k-mesh is Gamma-centred like the other codes", "ok": bool(k and k.group(4) == "True"),
                  "detail": k.group(0) if k else "no kpts"}]
        return ReadBack(atoms=atoms, kmesh=[int(x) for x in k.group(1, 2, 3)] if k else None,
                        functional_ok=bool(xc) and xc.group(1) == XC[req.functional], functional_detail=f"xc={xc.group(1) if xc else None}",
                        extra_checks=extra)

    def run_args(self, outdir: Path) -> dict:
        return {"program": self.program, "args": ["python", "gpaw_scf.py"], "stdout": "gpaw.out"}

    def parse_results(self, rundir: Path) -> Results | None:
        txt = rundir / "gpaw.txt"
        if not txt.is_file():
            return None
        text = txt.read_text(errors="replace")
        e = re.findall(r"Extrapolated:\s*([-\d.]+)", text)
        conv = re.search(r"Converged in (\d+) steps", text)
        ef = re.findall(r"Fermi level:\s*([-\d.]+)", text)
        gap = re.findall(r"^Gap:\s*([-\d.]+)\s*eV", text, re.M)
        return Results(converged=bool(conv), total_energy_eV=float(e[-1]) if e else None, fermi_eV=float(ef[-1]) if ef else None,
                       gap_eV=float(gap[-1]) if gap else None, scf_iterations=int(conv.group(1)) if conv else None,
                       warnings=[] if conv else ["GPAW did not report convergence"], raw={"energy_reference": "isolated atoms"})
